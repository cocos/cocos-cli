// Keep the network boundary aligned with the CLI's declared scene API, excluding local UI/lifecycle services.
const ts = require('typescript');
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const config = ts.readConfigFile(path.join(root, 'tsconfig.json'), ts.sys.readFile);
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
const filename = path.join(root, 'src/core/scene/scene-process/service/interfaces.ts');
const program = ts.createProgram([filename], parsed.options);
const checker = program.getTypeChecker();
const source = program.getSourceFile(filename);
const declaration = source.statements.find(node => ts.isInterfaceDeclaration(node) && node.name.text === 'IPublicServiceManager');
const modules = new Set(['Editor', 'Node', 'Component', 'Prefab', 'Selection', 'Undo', 'Redo', 'ReferenceImage', 'Terrain']);
const result = {};
for (const property of checker.getPropertiesOfType(checker.getTypeAtLocation(declaration))) {
    if (!modules.has(property.name)) continue;
    const type = checker.getTypeOfSymbolAtLocation(property, declaration);
    result[property.name] = checker.getPropertiesOfType(type)
        .filter(method => checker.getTypeOfSymbolAtLocation(method, declaration).getCallSignatures().length)
        .map(method => method.name).sort();
}
// These editor operations already exist in the backend but are intentionally absent from the MCP-facing API.
result.Node.push('setProperty', 'resetProperty', 'setParent', 'reorder', 'duplicate', 'paste', 'copy', 'cut');
result.Component.push('setProperty');
result.Editor.push('applyRecordedChanges');
result.Undo = ['undo', 'isDirty', 'canUndo'];
result.Redo = ['redo', 'canRedo'];
for (const name of Object.keys(result)) result[name] = [...new Set(result[name])].sort();
const content = '// Generated by workflow/generate-scene-session-methods.js. Review additions as public RPC surface.\n'
    + 'export const sceneSessionMethods: Record<string, readonly string[]> = ' + JSON.stringify(result, null, 4) + ';\n';
const target = path.join(root, 'src/core/scene/session/methods.ts');
if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== content) throw new Error('Scene session method contract is stale');
} else fs.writeFileSync(target, content);
